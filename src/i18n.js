let current = 'es';
export function setLang(code) { current = DICTS[code] ? code : 'es'; return current; }
export function getLang() { return current; }
export function langInfo(code = current) { return LANGS.find((l) => l.code === code) ?? LANGS[0]; }

/** Traduce. {vars} se sustituyen. Sufijo _1 para el singular. */
export function t(key, vars = null, lang = current) {
  let k = key;
  if (vars && typeof vars.n === 'number' && vars.n === 1 && (DICTS[lang]?.[`${key}_1`] || ES[`${key}_1`])) {
    k = `${key}_1`;
  }
  let s = DICTS[lang]?.[k] ?? EN[k] ?? ES[k] ?? DICTS[lang]?.[key] ?? EN[key] ?? ES[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, v) => (vars[v] ?? ''));
  return s;
}

